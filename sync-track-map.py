    domains = track["domains"]
    lines = [
        f"# {track['track']}",
        "",
        "<!-- generated by ./sync-track-map.py; edit the graph/classifier, then regenerate -->",
        "",
        f"Track number: `{index:02d}`",
        "",
        f"Wrapper count: `{track['function_count']}`",
        "",
        "This directory is a standalone track project. You can enter it, build it,",
        "run it, and edit its source without depending on the top-level playground",
        "driver.",
        "",
        "```sh",
        f"cd tracks/{index:02d}-{slug(track['track'])}",
        "./run.sh",
        "./test.sh",
        "```",
        "",
        "Curated lesson guide: [TRACK.md](./TRACK.md).",
        "",
        "## Purpose",
        "",
        track["purpose"],
        "",
        "## Domains",
        "",
    ]
    lines.extend(f"- `{domain}` ({graph['domains'][domain]['count']} wrappers)" for domain in domains)
    lines.extend(
        [
            "",
            "## Suggested lesson arc",
            "",
            "1. Start with a valid, idiomatic example that uses only p101 wrappers.",
            "2. Introduce one broken fixture or commented-out trap.",
            "3. Run the playground/tooling check and read the diagnostic.",
            "4. Fix the code, re-run the check, and compare the event/report output.",
            "5. Add one regression test or corpus expectation before moving on.",
            "",
            "## Wrapper inventory",
            "",
        ]
    )
    for domain in domains:
        funcs = domain_functions(graph, domain)
        lines.extend([f"### `{domain}`", "", markdown_list(funcs), ""])
