def track_json(graph: dict[str, Any], track: dict[str, Any], index: int) -> str:
    data = {
        "track": track["track"],
        "title": track["track"].replace("-", " "),
        "order": index,
        "generated": True,
        "wrapper_count": track["function_count"],
        "purpose": track["purpose"],
        "domains": [
            {
                "name": domain,
                "function_count": graph["domains"][domain]["count"],
                "functions": domain_functions(graph, domain),
            }
            for domain in track["domains"]
        ],
        "local_project": {
            "source": "src/main.c",
            "header": "include/track_info.h",
            "binary": f"p101-track-{slug(track['track'])}",
        },
    }
    return json.dumps(data, indent=2) + "\n"


def track_header(track: dict[str, Any], index: int) -> str:
    guard = f"P101_TRACK_{index:02d}_{slug(track['track']).upper().replace('-', '_')}_INFO_H"
    return "\n".join(
        [
            f"#ifndef {guard}",
            f"#define {guard}",
            "",
            f"#define P101_TRACK_SLUG {c_string(track['track'])}",
            f"#define P101_TRACK_TITLE {c_string(track['track'].replace('-', ' '))}",
            f"#define P101_TRACK_PURPOSE {c_string(track['purpose'])}",
            "",
            "enum",
            "{",
            f"    P101_TRACK_INDEX         = {index},",
            f"    P101_TRACK_WRAPPER_COUNT = {track['function_count']}",
            "};",
            "",
            f"#endif /* {guard} */",
            "",
        ]
    )


def track_main(graph: dict[str, Any], track: dict[str, Any], index: int) -> str:
    functions: list[str] = []
    for domain in track["domains"]:
        functions.extend(domain_functions(graph, domain))
    if not functions:
        functions = ["none"]
    function_lines = ",\n".join(f"    {c_string(function)}" for function in functions)
    extra_includes: list[str] = []
    demo_function: list[str] = []
    demo_call: list[str] = []
    if track["track"] == "c-memory-bytes":
        extra_includes = [
            "#include <inttypes.h>",
            "#include <p101_util/endian.h>",
        ]
        demo_function = [
            "",
            "static int write_endian_demo(const struct p101_env *env, struct p101_error *err)",
            "{",
            "    const uint32_t host_value = UINT32_C(0x12345678);",
            "    uint32_t       wire_value;",
            "    uint32_t       round_trip;",
            "",
            "    wire_value = p101_htobe32(env, host_value);",
            "    round_trip = p101_be32toh(env, wire_value);",
            "    if(p101_fprintf(env, err, stdout, \"Endian round trip: 0x%08\" PRIx32 \" -> 0x%08\" PRIx32 \" -> 0x%08\" PRIx32 \"\\n\", host_value, wire_value, round_trip) < 0 || p101_error_has_error(err))",
            "    {",
            "        return EXIT_FAILURE;",
            "    }",
            "",
            "    return (round_trip == host_value) ? EXIT_SUCCESS : EXIT_FAILURE;",
            "}",
        ]
        demo_call = [
            "    if(write_endian_demo(env, err) != EXIT_SUCCESS)",
            "    {",
            "        goto done;",
            "    }",
            "",
        ]
    return "\n".join(
        [
            '#include "track_info.h"',
            "#include <p101_c/p101_stdio.h>",
            "#include <p101_c/p101_stdlib.h>",
            "#include <p101_env/env.h>",
            "#include <p101_error/error.h>",
            *extra_includes,
            "#include <stddef.h>",
            "#include <stdlib.h>",
            "",
            "static const char *const wrapper_functions[] = {",
            function_lines,
            "};",
            "",
            "static const size_t wrapper_function_count = sizeof(wrapper_functions) / sizeof(wrapper_functions[0]);",
            "",
            "static int write_line(const struct p101_env *env, struct p101_error *err, const char *line)",
            "{",
            "    int ret_val;",
            "",
            "    ret_val = p101_fprintf(env, err, stdout, \"%s\\n\", line);",
            "    if(ret_val < 0 || p101_error_has_error(err))",
            "    {",
            "        return EXIT_FAILURE;",
            "    }",
            "",
            "    return EXIT_SUCCESS;",
            "}",
            "",
            "static int write_wrapper_inventory(const struct p101_env *env, struct p101_error *err)",
            "{",
            "    int ret_val;",
            "",
            "    ret_val = EXIT_SUCCESS;",
            "    for(size_t i = 0; i < wrapper_function_count; i++)",
            "    {",
            "        if(p101_fprintf(env, err, stdout, \"- %s\\n\", wrapper_functions[i]) < 0 || p101_error_has_error(err))",
            "        {",
            "            ret_val = EXIT_FAILURE;",
            "            break;",
            "        }",
            "    }",
            "",
            "    return ret_val;",
            "}",
            *demo_function,
            "",
            "int main(void)",
            "{",
            "    struct p101_error *err;",
            "    struct p101_env   *env;",
            "    int                ret_val;",
            "",
            "    ret_val = EXIT_FAILURE;",
            "    err     = p101_error_create(false);",
            "    if(err == NULL)",
            "    {",
            "        return EXIT_FAILURE;",
            "    }",
            "",
            "    env = p101_env_create(err, NULL);",
            "    if(env == NULL || p101_error_has_error(err))",
            "    {",
            "        goto done;",
            "    }",
            "",
            "    if(p101_fprintf(env, err, stdout, \"Track %d: %s\\n\", P101_TRACK_INDEX, P101_TRACK_TITLE) < 0 || p101_error_has_error(err))",
            "    {",
            "        goto done;",
            "    }",
            "    if(write_line(env, err, P101_TRACK_PURPOSE) != EXIT_SUCCESS)",
            "    {",
            "        goto done;",
            "    }",
            "    if(p101_fprintf(env, err, stdout, \"Wrapper count: %d\\n\", P101_TRACK_WRAPPER_COUNT) < 0 || p101_error_has_error(err))",
            "    {",
            "        goto done;",
            "    }",
            "    if(write_line(env, err, \"Wrappers in this track:\") != EXIT_SUCCESS)",
            "    {",
            "        goto done;",
            "    }",
            "    if(write_wrapper_inventory(env, err) != EXIT_SUCCESS)",
            "    {",
            "        goto done;",
            "    }",
            "",
            *demo_call,
            "    ret_val = EXIT_SUCCESS;",
            "",
            "done:",
            "    p101_env_destroy(env);",
            "    p101_error_destroy(err);",
            "    return ret_val;",
            "}",
            "",
        ]
    )


