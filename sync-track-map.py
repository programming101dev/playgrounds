def materialize_track_project(graph: dict[str, Any], track: dict[str, Any], index: int) -> None:
    track_dir = TRACKS / f"{index:02d}-{slug(track['track'])}"
    track_dir.mkdir(parents=True, exist_ok=True)

    for name, target in SHARED_LINKS.items():
        ensure_symlink(track_dir / name, target)

    write(track_dir / "README.md", track_readme(graph, track, index))
    write(track_dir / "TRACK.md", track_lesson(track, index))
    write(track_dir / "track.json", track_json(graph, track, index))
    write(track_dir / "include" / "track_info.h", track_header(track, index))
    main_source = track_dir / "src" / "main.c"
    write(main_source, track_main(graph, track, index))
    format_c(main_source)
    write(track_dir / "config.cmake", track_config(track, index))
    write(track_dir / "test" / "CMakeLists.txt", track_test_cmake(track))
    write_executable(track_dir / "run.sh", (PLAYGROUND / "track-runner.sh").read_text(encoding="utf-8"))


def tracks_index(graph: dict[str, Any], tracks: list[dict[str, Any]]) -> str:
    repo = graph["repository_recommendation"]
    lines = [
        "# Playground tracks",
        "",
        "<!-- generated by ./sync-track-map.py; edit the graph/classifier, then regenerate -->",
        "",
        "The playground is one repository with many small tracks. The goal is to",
        "replace the old wrapper-example sprawl with focused, teachable playground",
        "areas while still covering every p101 wrapper exactly once.",
        "",
        "## Coverage",
        "",
        f"- Wrappers covered: `{repo['covered_function_count']}`",
        f"- Uncovered wrappers/domains: `{repo['uncovered_function_count']}`",
        f"- Track count: `{repo['track_count']}`",
        "- Orientation pre-track: `00-p101-orientation`",
        "- Misc tracks/domains are intentionally forbidden.",
        "",
        "## Track list",
        "",
        "| # | Track | Wrappers | Purpose |",
        "| ---: | --- | ---: | --- |",
        "| 00 | [`p101-orientation`](00-p101-orientation/README.md) | 0 | Hand-authored pre-track for env, err, wrappers, and tools. |",
    ]
    for index, track in enumerate(tracks, start=1):
        path = f"{index:02d}-{slug(track['track'])}/README.md"
        lines.append(f"| {index:02d} | [`{track['track']}`]({path}) | {track['function_count']} | {track['purpose']} |")
    lines.extend(
        [
            "",
            "## How to use this",
            "",
            "Each track directory is a standalone project with local source,",
            "metadata, build configuration, a smoke test, and a runner. A finished",
            "track should start from good examples, then add issue-focused labs",
            "where students uncomment or repair intentionally bad code and watch the",
            "checks improve.",
            "",
            "Regenerate after changing wrapper libraries or graph classification:",
            "",
            "```sh",
            "../../scripts/generators/analyze-lib-function-graph.py",
            "./sync-track-map.py",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def manifest(graph: dict[str, Any], tracks: list[dict[str, Any]]) -> str:
    data = {
        "source": str(GRAPH.relative_to(ROOT)),
        "repository": graph["repository_recommendation"]["repository"],
        "orientation_track": {
            "index": 0,
            "track": "p101-orientation",
            "directory": "00-p101-orientation",
            "function_count": 0,
            "purpose": "Hand-authored pre-track for env, err, wrappers, and tools.",
        },
        "track_count": len(tracks),
        "covered_function_count": graph["repository_recommendation"]["covered_function_count"],
        "uncovered_function_count": graph["repository_recommendation"]["uncovered_function_count"],
        "tracks": [
            {
                "index": index,
                "track": track["track"],
                "directory": f"{index:02d}-{slug(track['track'])}",
                "function_count": track["function_count"],
                "purpose": track["purpose"],
                "domains": [
                    {
                        "name": domain,
                        "function_count": graph["domains"][domain]["count"],
                        "functions": domain_functions(graph, domain),
                    }
                    for domain in track["domains"]
                ],
            }
            for index, track in enumerate(tracks, start=1)
        ],
    }
    return json.dumps(data, indent=2) + "\n"


def main() -> int:
    graph = load_graph()
    repo = graph["repository_recommendation"]
    tracks = repo["tracks"]
    if repo["uncovered_function_count"] != 0:
        raise RuntimeError("track map has uncovered wrappers/domains")
    if any("misc" in domain for domain in graph["domains"]):
        raise RuntimeError("misc domains are not allowed")

    TRACKS.mkdir(parents=True, exist_ok=True)
    write(TRACKS / "README.md", tracks_index(graph, tracks))
    write(TRACKS / "manifest.json", manifest(graph, tracks))

    orientation = {
        "track": "p101-orientation",
        "function_count": 0,
        "purpose": "Learn env/error setup, the p101 wrapper boundary, and how the playground tools report what they observe.",
        "domains": [],
    }
    materialize_track_project(graph, orientation, 0)

    for index, track in enumerate(tracks, start=1):
        materialize_track_project(graph, track, index)

    print(f"wrote {TRACKS / 'README.md'}")
    print(f"wrote {TRACKS / 'manifest.json'}")
    print(f"wrote {len(tracks) + 1} standalone track projects under {TRACKS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
